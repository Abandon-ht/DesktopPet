let currentLanguage = 'zh-CN';
const sourceText = new WeakMap();
const sourcePlaceholder = new WeakMap();
function t(source) {
  const index = {'en-US':0,'ja-JP':1,'ko-KR':2}[currentLanguage];
  return index === undefined ? source : (translations[source]?.[index] ?? source);
}
function applyLanguage(language) {
  currentLanguage = language;
  document.documentElement.lang = language;
  document.title = language === 'zh-CN' ? 'DesktopPet · 角色与设置' : 'DesktopPet · Settings';
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  while (walker.nextNode()) {
    const node = walker.currentNode;
    if (!sourceText.has(node)) sourceText.set(node, node.nodeValue);
    const original = sourceText.get(node);
    const trimmed = original.trim();
    if (trimmed && translations[trimmed]) node.nodeValue = original.replace(trimmed, t(trimmed));
  }
  document.querySelectorAll('[placeholder]').forEach(element => {
    if (!sourcePlaceholder.has(element)) sourcePlaceholder.set(element, element.placeholder);
    element.placeholder = t(sourcePlaceholder.get(element));
  });
  for (const selector of ['#voice-message','#care-message','#companion-message','#import-message']) {
    const element = document.querySelector(selector);
    const shown = element?.textContent;
    const source = Object.keys(translations).find(key => shown === key || translations[key].includes(shown));
    if (source) element.textContent = t(source);
  }
}
